    companion object {
        fun forLanguage(language: EditorLanguage): HighlightRules =
            when (language) {
                EditorLanguage.Kotlin -> kotlinRules()
                EditorLanguage.Java -> javaRules()
                EditorLanguage.Python -> pythonRules()
                EditorLanguage.JavaScript -> javaScriptRules()
                EditorLanguage.TypeScript -> typeScriptRules()
                EditorLanguage.JSON -> jsonRules()
                EditorLanguage.XML -> xmlRules()
                EditorLanguage.HTML -> htmlRules()
                EditorLanguage.CSS -> cssRules()
                EditorLanguage.C -> cRules()
                EditorLanguage.CPlus -> cPlusRules()
                EditorLanguage.Go -> goRules()
                EditorLanguage.Rust -> rustRules()
                EditorLanguage.Swift -> swiftRules()
                EditorLanguage.Shell -> shellRules()
                EditorLanguage.SQL -> sqlRules()
                EditorLanguage.Markdown -> markdownRules()
                EditorLanguage.PlainText -> plainTextRules()
                EditorLanguage.Toml -> plainTextRules()
                EditorLanguage.Yaml -> plainTextRules()
                // 其余（Ini/Log/Smali 等）由 createSyntaxHighlighter 分流到专用高亮器，
                // 此处兜底为纯文本，避免直接调用 forLanguage 时穷尽性报错。
                else -> plainTextRules()
            }

